import { readdir, readFile, writeFile, mkdir, cp, stat, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { iconPng, iconSvg, androidIcon } from './icon-artwork.mjs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { buildPublishing } from './publishing.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const publicDir=path.join(root,'public');
async function files(dir){
  const result=[];
  for(const entry of await readdir(dir,{withFileTypes:true})){
    if(entry.name.startsWith('.'))continue;
    const name=path.join(dir,entry.name);
    if(entry.isDirectory())result.push(...await files(name));else if(entry.isFile())result.push(name);
  }return result.sort();
}
export async function buildMobile(){
  await buildPublishing();
  await writeFile(path.join(publicDir,'icon.svg'),iconSvg());
  await mkdir(path.join(publicDir,'icons'),{recursive:true});
  for(const[name,size]of[['icon-192.png',192],['icon-512.png',512],['maskable-512.png',512],['apple-touch-icon.png',180]])await writeFile(path.join(publicDir,'icons',name),iconPng(size));
  const res=path.join(root,'android/app/src/main/res');
  await writeFile(path.join(res,'drawable/cfa_mark.xml'),androidIcon({foreground:true}));
  await writeFile(path.join(res,'drawable-v24/ic_launcher_foreground.xml'),androidIcon({foreground:true}));
  for(const name of ['ic_launcher.xml','ic_launcher_round.xml'])await writeFile(path.join(res,'mipmap-anydpi',name),androidIcon());
  for(const[density,size]of[['mdpi',48],['hdpi',72],['xhdpi',96],['xxhdpi',144],['xxxhdpi',192]]){
    const dir=path.join(res,'mipmap-'+density);
    for(const name of ['ic_launcher.png','ic_launcher_round.png'])await writeFile(path.join(dir,name),iconPng(size));
    await writeFile(path.join(dir,'ic_launcher_foreground.png'),iconPng(size*108/48,{foreground:true}));
  }
  const assets=(await files(publicDir)).filter(file=>path.basename(file)!=='precache-manifest.js');const hash=createHash('sha256');
  for(const file of assets){hash.update(path.relative(publicDir,file));hash.update(await readFile(file));}
  const version=hash.digest('hex').slice(0,16);
  const precache=['/',...assets.filter(file=>path.basename(file)!=='sw.js').map(file=>'/'+path.relative(publicDir,file).split(path.sep).join('/'))];
  await writeFile(path.join(publicDir,'precache-manifest.js'),`// Generated by node scripts/build-mobile.mjs\nself.CFA_CACHE_VERSION = ${JSON.stringify(version)};\nself.CFA_PRECACHE = ${JSON.stringify(precache,null,2)};\n`);
  const dist=path.join(root,'mobile-site','dist');
  try{if((await stat(dist)).isDirectory()&&!(await readdir(dist)).includes('.cfa-mobile-output'))throw new Error('mobile-site/dist exists without a build marker; refusing to overwrite it.');}catch(error){if(error.code!=='ENOENT')throw error;}
  await mkdir(dist,{recursive:true});await writeFile(path.join(dist,'.cfa-mobile-output'),'Generated CFA Pocket static output.\n');for (const file of ['account.js','delete-account.html','delete-account-page.js']) await rm(path.join(dist,file),{force:true});await cp(publicDir,dist,{recursive:true});
  await writeFile(path.join(dist,'.nojekyll'),'');
  const distManifest=JSON.parse(await readFile(path.join(dist,'manifest.webmanifest'),'utf8'));
  distManifest.id='./';distManifest.start_url='./#home';distManifest.scope='./';
  if(Array.isArray(distManifest.icons))distManifest.icons=distManifest.icons.map(i=>({...i,src:i.src.replace(/^\//,'./')}));
  if(Array.isArray(distManifest.shortcuts))distManifest.shortcuts=distManifest.shortcuts.map(s=>({...s,url:s.url.replace(/^\//,'./')}));
  await writeFile(path.join(dist,'manifest.webmanifest'),JSON.stringify(distManifest,null,2)+'\n');
  return{version,assets:precache.length,directory:dist};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(await buildMobile()));
